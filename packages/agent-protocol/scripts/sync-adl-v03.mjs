#!/usr/bin/env node
// sync-adl-v03.mjs
//
// ADL v0.3 is owned by nissan/reddiagent-lab (specs/ADL-v0.3.schema.json and
// scripts/adl_v03_conformance.py). This package carries a copy of the schema
// and of the lab's v0.3 examples, plus the lab checker's verdict on each, so
// the TypeScript validator can be held to the Python one offline.
//
//   node scripts/sync-adl-v03.mjs --lab ../../../reddiagent-lab          copy and regenerate
//   node scripts/sync-adl-v03.mjs --lab ../../../reddiagent-lab --check  fail if the copies are stale
//
// Regenerating the verdicts runs the lab's own checker (Python 3.12+, pyyaml,
// jsonschema). Nothing here touches the network.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const labArg = args[args.indexOf('--lab') + 1];
if (!args.includes('--lab') || !labArg) {
  console.error('usage: sync-adl-v03.mjs --lab <path to reddiagent-lab> [--check]');
  process.exit(2);
}
const lab = resolve(labArg);
const check = args.includes('--check');

const schemaText = readFileSync(join(lab, 'specs/ADL-v0.3.schema.json'), 'utf8');
const schemaHash = createHash('sha256').update(schemaText).digest('hex');
const labCommit = (() => {
  try {
    return execFileSync('git', ['-C', lab, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
})();

const BEGIN = '// BEGIN GENERATED ADL v0.3 SCHEMA\n';
const END = '// END GENERATED ADL v0.3 SCHEMA\n';
// The schema lives at the end of src/adl.ts, not in a module of its own, so the
// app can compile the package source without resolving a relative import.
const schemaBlock = `${BEGIN}// Generated by scripts/sync-adl-v03.mjs from nissan/reddiagent-lab
// specs/ADL-v0.3.schema.json (sha256 ${schemaHash}). Do not edit by hand.

/** SHA-256 of the lab's ADL v0.3 JSON Schema this copy was made from. */
export const ADL_V03_SCHEMA_SHA256 = "${schemaHash}";

/** The ADL v0.3 JSON Schema (draft 2020-12). */
export const ADL_V03_SCHEMA: Record<string, unknown> = ${JSON.stringify(JSON.parse(schemaText), null, 2)};
${END}`;

const fixturesDir = join(pkgDir, 'tests/fixtures/adl-v03');
const sources = [
  ...readdirSync(join(lab, 'examples/v0.3')).filter((f) => f.endsWith('.yaml')).map((f) => ({ from: join(lab, 'examples/v0.3', f), name: `valid/${f}` })),
  ...readdirSync(join(lab, 'examples/invalid')).filter((f) => f.startsWith('adl-v0.3-') && f.endsWith('.yaml')).map((f) => ({ from: join(lab, 'examples/invalid', f), name: `invalid/${f}` })),
].sort((a, b) => a.name.localeCompare(b.name));

const adlPath = join(pkgDir, 'src/adl.ts');
const adlSource = readFileSync(adlPath, 'utf8');
const begin = adlSource.indexOf(BEGIN);
const end = adlSource.indexOf(END);
if (begin < 0 || end < begin) {
  console.error('src/adl.ts has no generated schema markers.');
  process.exit(1);
}
const withSchema = adlSource.slice(0, begin) + schemaBlock + adlSource.slice(end + END.length);
if (check) {
  const problems = [];
  if (adlSource !== withSchema) problems.push('src/adl.ts (generated schema block)');
  for (const s of sources) {
    const target = join(fixturesDir, s.name);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== readFileSync(s.from, 'utf8')) problems.push(`tests/fixtures/adl-v03/${s.name}`);
  }
  if (problems.length) {
    console.error(`ADL v0.3 copies are stale against ${lab} (${labCommit}):\n  ${problems.join('\n  ')}\nRun: node scripts/sync-adl-v03.mjs --lab ${labArg}`);
    process.exit(1);
  }
  console.log(`ADL v0.3 copies match ${lab} (${labCommit}).`);
  process.exit(0);
}

writeFileSync(adlPath, withSchema);
rmSync(fixturesDir, { recursive: true, force: true });
mkdirSync(join(fixturesDir, 'valid'), { recursive: true });
mkdirSync(join(fixturesDir, 'invalid'), { recursive: true });
const expected = {};
for (const s of sources) {
  writeFileSync(join(fixturesDir, s.name), readFileSync(s.from, 'utf8'));
  let out;
  try {
    out = execFileSync('python3', ['scripts/adl_v03_conformance.py', s.from], { cwd: lab, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (error) {
    out = error.stdout;
  }
  const parsed = JSON.parse(out);
  const report = Array.isArray(parsed) ? parsed[0] : parsed.reports?.[0] ?? parsed;
  expected[s.name] = {
    status: report.status,
    requestedLevel: report.requestedLevel,
    achievedLevel: report.achievedLevel,
    schemaValid: report.schemaDiagnostics.length === 0,
    missingFieldsByLevel: report.missingFieldsByLevel,
    forbiddenCapabilitiesByLevel: report.forbiddenCapabilitiesByLevel,
  };
}
writeFileSync(join(fixturesDir, 'expected.json'), `${JSON.stringify({ labCommit, schemaSha256: schemaHash, reports: expected }, null, 2)}\n`);
console.log(`Copied the ADL v0.3 schema and ${sources.length} examples from ${lab} (${labCommit}).`);
