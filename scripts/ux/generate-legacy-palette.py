import re,sys
theme=open(sys.argv[1]).read()
val={m[0]:m[1] for m in re.findall(r'--color-([a-z]+-\d+):\s*([^;]+);',theme)}
steps=[50,100,200,300,400,500,600,700,800,900,950]
chrom="red orange amber yellow lime green emerald teal cyan sky blue indigo violet purple fuchsia pink rose".split()
inv={50:950,100:900,200:800,300:700,400:700,500:500,600:400,700:300,800:200,900:100,950:50}
warm={50:'#14161a',100:'#1a1c1f',200:'#23262a',300:'#33362f',400:'#4a4d48',500:'#5f625b',600:'#8a877c',700:'#c9c3b2',800:'#ddd6c5',900:'#ebe5d6',950:'#f4f0e6'}
grays="slate gray zinc neutral stone".split()
light=[];dark=[]
for f in chrom:
  src='violet' if f in('indigo','purple') else f
  for s in steps:
    light.append(f"  --color-{f}-{s}: {val[f'{src}-{inv[s]}']};")
    dark.append(f"  --color-{f}-{s}: {val[f'{f}-{s}']};")
for f in grays:
  for s in steps:
    light.append(f"  --color-{f}-{s}: {warm[s]};")
    # Tailwind's gray-500 misses 4.5:1 on the dark page; lift it one step.
    dark.append(f"  --color-{f}-{s}: {val[f'{f}-{400 if s==500 else s}']};")
light+= ["  --color-white: #14161a;","  --color-black: #f4f0e6;"]
dark += ["  --color-white: #fff;","  --color-black: #000;"]
print("/* Generated by scripts/ux/generate-legacy-palette.py: do not edit by hand. */")
print("/* Light theme: the dark-era palette utilities (text-white, text-gray-400, bg-white/5 ...)")
print("   are remapped to paper-and-ink equivalents so every page follows the marketing look.")
print("   Dark theme (OS setting or data-theme=\"dark\") restores Tailwind's own values. */")
print(":root {\n"+"\n".join(light)+"\n}")
blk="\n".join(dark)
print('@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n'+"\n".join("  "+l for l in dark)+"\n  }\n}")
print(':root[data-theme="dark"] {\n'+blk+"\n}")
