#!/usr/bin/env bash
# Copies the Anchor escrow tests that cover the V1 instructions into
# equivalence/tests, changing only where the program binary is loaded from, so
# the same assertions run against the Pinocchio build.
#
#   scripts/sync-equivalence-tests.sh          regenerate the copies
#   scripts/sync-equivalence-tests.sh --check  fail if the copies are stale
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_dir="$here/../../archive/anchor-escrow/tests"
out_dir="$here/equivalence/tests"
# reputation.rs, attestation.rs and per.rs need the `extended` feature on both
# programs. litesvm_runtime_profile.rs tests the simulator, not a program.
files=(test_escrow.rs test_token_escrow.rs test_token2022_escrow.rs test_registry.rs
       instruction_surface.rs mollusk_runtime.rs reputation.rs attestation.rs per.rs)

render() {
  printf '// GENERATED by scripts/sync-equivalence-tests.sh from archive/anchor-escrow/tests/%s.\n' "$1"
  printf '// Do not edit: change the source test and regenerate.\n'
  sed -e 's#"\.\./\.\./\.\./target/deploy/escrow\.so"#"../../target/deploy/pinocchio_escrow.so"#' \
      -e 's#join("\.\./\.\./target/deploy")#join("../target/deploy")#' \
      -e 's#Mollusk::new(&escrow::id(), "escrow")#Mollusk::new(\&escrow::id(), "pinocchio_escrow")#' \
      "$source_dir/$1"
}

status=0
mkdir -p "$out_dir/fixtures"
for file in "${files[@]}"; do
  if [[ "${1:-}" == "--check" ]]; then
    if ! diff -q <(render "$file") "$out_dir/$file" >/dev/null 2>&1; then
      echo "stale: equivalence/tests/$file" >&2
      status=1
    fi
  else
    render "$file" > "$out_dir/$file"
  fi
done
for fixture in "$source_dir"/fixtures/*; do
  if [[ "${1:-}" == "--check" ]]; then
    cmp -s "$fixture" "$out_dir/fixtures/$(basename "$fixture")" || { echo "stale: fixtures/$(basename "$fixture")" >&2; status=1; }
  else
    cp "$fixture" "$out_dir/fixtures/"
  fi
done
exit "$status"
